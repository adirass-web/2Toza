#!/usr/bin/env python3
"""One-off: outline the approved wordmark (italic 'toza' in Bona Nova + vertical 閉ざす in Noto Serif CJK)
into assets/brand/toza-wordmark.svg (single path, fill=currentColor). Fonts are OFL; no font file ships.
Usage: python3 scripts/tools/make-wordmark.py <bona-nova-latin-400-italic.woff2> <kanji-serif.woff2>"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

latin, kanji = TTFont(sys.argv[1]), TTFont(sys.argv[2])
def glyphs(font, text, scale, x0, y0, track, vertical=False):
    cmap, gs, hm = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    pen = SVGPathPen(gs); x, y = x0, y0
    for ch in text:
        name = cmap[ord(ch)]
        # SVG y axis points down: flip, place baseline at y
        tp = TransformPen(pen, (scale, 0, 0, -scale, x, y))
        gs[name].draw(tp)
        if vertical: y += font["head"].unitsPerEm * scale + track
        else: x += hm[name][0] * scale + track
    return pen.getCommands(), x, y
S_LAT = 0.1            # 1000 upem -> 100 px em
t1, xe, _ = glyphs(latin, "toza", S_LAT, 0, 80, -0.045 * 100)
# kanji column: 0.31 of the latin em, upright, 0.2em tracking, top-aligned with the latin line
S_K = 0.028
kx = xe + 8
# first kanji baseline at 0.88 em below the column top (y = 8)
t2, _, ye = glyphs(kanji, "閉ざす", S_K, kx, 0.88 * 28 + 8, 0.12 * 28, vertical=True)
W, H = round(kx + 30, 1), 102
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" role="img" aria-labelledby="t">'
       f'<title id="t">toza</title><path fill="currentColor" d="{t1}{t2}"/></svg>\n')
open("assets/brand/toza-wordmark.svg", "w").write(svg)
# inline version for templates: decorative (the link carries the accessible name), sized by its wrapper
inline = svg.replace('role="img" aria-labelledby="t">', 'class="h-full w-auto" aria-hidden="true" focusable="false">').replace('<title id="t">toza</title>', '')
open("src/_includes/wordmark.njk", "w").write("{#- Generated by scripts/tools/make-wordmark.py. Outlined wordmark, fill follows the text colour. -#}\n" + inline)
print("wrote assets/brand/toza-wordmark.svg", W, H, len(svg), "bytes")
